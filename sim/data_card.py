"""Writes data_card.md: realism checks on the simulated data, with real results."""
from __future__ import annotations

import statistics
from typing import Any

from core.config import ROOT, load
from core.shares import lane_shares

Event = dict[str, Any]


def _minute(t: float) -> int:
    return int(t // 60) + 1


def _quantile(values: list[float], q: float) -> float:
    s = sorted(values)
    return s[min(len(s) - 1, int(q * len(s)))]


def _completion(passes: list[Event]) -> float:
    return sum(p["outcome"] == "success" for p in passes) / max(1, len(passes))


def _zone(x: float) -> str:
    p = load()["pitch"]
    return "own" if x < p["own_third_x"] else ("final" if x > p["final_third_x"] else "middle")


def league_checks(league: list[list[Event]]) -> list[tuple[str, float, list[float]]]:
    rng = load()["data_card"]
    goals = [sum(e["type"] == "goal" for e in m) for m in league]
    shots = [e for m in league for e in m if e["type"] == "shot"]
    passes = [e for m in league for e in m if e["type"] == "pass"]
    return [
        ("Goals per match (league mean)", statistics.mean(goals), rng["goals_per_match"]),
        ("Shots per team per match", len(shots) / (2 * len(league)), rng["shots_per_team"]),
        ("xG per shot (mean)", statistics.mean(e["xg"] for e in shots), rng["xg_per_shot"]),
        ("Pass completion (all passes)", _completion(passes), rng["pass_completion"]),
    ]


def zone_table(league: list[list[Event]]) -> dict[str, float]:
    passes = [e for m in league for e in m if e["type"] == "pass"]
    return {z: _completion([p for p in passes if _zone(p["x"]) == z]) for z in ("own", "middle", "final")}


def story_checks(hero: list[Event]) -> list[tuple[str, str, bool]]:
    s = load()["sim"]
    own_x = load()["pitch"]["own_third_x"]
    subs = [e for e in hero if e["type"] == "substitution" and e["team"] == "NOR"]
    goals = [e for e in hero if e["type"] == "goal"]
    before = [e for e in hero if s["hero_sub_t"] - 900 <= e["t"] < s["hero_sub_t"]]
    after = [e for e in hero if s["hero_sub_t"] <= e["t"] < s["hero_overload_until_t"]]
    left_b, n_b = lane_shares(before, "NOR")
    left_a, n_a = lane_shares(after, "NOR")
    losses = [e for e in hero if e["type"] == "possession_change" and e["team"] == "HAR" and e["x"] < own_x]
    split = s["hero_press_from_t"]
    rate_b = sum(e["t"] < split for e in losses) / (split / 600)
    rate_a = sum(e["t"] >= split for e in losses) / ((5400 - split) / 600)
    return [
        ("Northbridge substitution at 58'", f"minute {[_minute(e['t']) for e in subs]}",
         any(_minute(e["t"]) == 58 for e in subs)),
        ("Goal at 63'", f"goals at {[(_minute(e['t']), e['team']) for e in goals]}",
         [_minute(e["t"]) for e in goals] == [63]),
        ("Left-flank overload after the sub", f"NOR left share {left_b['left']:.0%} (n={n_b}) in the 15 min before, "
         f"{left_a['left']:.0%} (n={n_a}) from 58' to 75'", left_a["left"] > 0.5 and left_a["left"] > left_b["left"]),
        ("Harlow own-third losses rise from 65'", f"{rate_b:.1f} per 10 min before, {rate_a:.1f} per 10 min after",
         rate_a > rate_b),
    ]


def write_data_card(hero: list[Event], league: list[list[Event]], seed: int, mu: float) -> None:
    shots = [e["xg"] for m in league for e in m if e["type"] == "shot"]
    hero_range = load()["data_card"]["hero_events"]
    lines = ["# Data card", "",
             f"Generated by `python -m sim.generate --seed {seed}`. All data is synthetic; clubs and players are fictional.",
             f"Hero match: Northbridge v Harlow, {len(hero)} events. Background league: {len(league)} matches from the same "
             "engine with no planted story, used only for the league mean xG and the checks below.",
             "In the hero match the only goal is scripted (63'); random shots there cannot score.",
             "Ranges are plausibility bands we chose (config.yaml), not targets fitted to real football data.", "",
             "## Realism checks", "", "| check | result | plausible range | pass |", "|---|---|---|---|"]
    for name, val, (lo, hi) in league_checks(league):
        lines.append(f"| {name} | {val:.3f} | {lo} to {hi} | {'PASS' if lo <= val <= hi else 'FAIL'} |")
    n_ok = hero_range[0] <= len(hero) <= hero_range[1]
    lines.append(f"| Hero match events | {len(hero)} | {hero_range[0]} to {hero_range[1]} | {'PASS' if n_ok else 'FAIL'} |")
    zones = zone_table(league)
    order_ok = zones["own"] > zones["middle"] > zones["final"]
    lines += ["", "## Pass completion by zone (league)", "", "| zone (by pass origin) | completion |", "|---|---|"]
    lines += [f"| {z} third | {v:.1%} |" for z, v in zones.items()]
    lines += ["", f"Own > middle > final: {'PASS' if order_ok else 'FAIL'}", "",
              "## Shot xG distribution (league)", "",
              f"{len(shots)} shots. p10 {_quantile(shots, 0.1):.3f}, median {_quantile(shots, 0.5):.3f}, "
              f"p90 {_quantile(shots, 0.9):.3f}, share above 0.3: {sum(v > 0.3 for v in shots) / len(shots):.1%}.", "",
              f"League mean xG per team per minute (mu, used by win probability): {mu:.5f}", "",
              "## Planted story (hero match)", "", "| element | observed | pass |", "|---|---|---|"]
    lines += [f"| {n} | {obs} | {'PASS' if ok else 'FAIL'} |" for n, obs, ok in story_checks(hero)]
    (ROOT / "data_card.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
